"""Every legacy-font table in one plain, standard form: tables/export/<font key>.tsv in the format of the Unicode Consortium / Apple mapping files (one line per typed code:
`0xCODE<TAB>0xUNICODE[+0xUNICODE...]<TAB># character`, a '+' between the code points of a sequence), and tables/export/index.tsv (font key, script, kind of table, where it
comes from, number of codes, whether the font also needs context rules). The text of a code is what layout.legacy_tables.decode gives for that code alone; glyph pieces that
only make a letter together (prefix vowel signs, reph, half forms) are put in order by legacy_tables.sequence, which the files cannot express (index column `context`).
python tools/export_tables.py"""
import collections
import csv
import json
import os
import sys
import unicodedata

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
from dspages.layout import legacy_fit as F, legacy_tables as T

OUT = os.path.join(T.TABLES, "export")
CONTEXT = {"padma", "preeti", "ml", "nudi", "bijoy", "geet", "priya", "pun", "chain", "labelled"}      # kinds whose text of a run is more than the text of its codes


def fmt(cp):
    return f"0x{ord(cp):02X}" if ord(cp) < 256 else f"0x{ord(cp):04X}"


def main():
    index = json.load(open(os.path.join(T.TABLES, "INDEX.json"), encoding="utf-8"))
    cov = json.load(open(os.path.join(T.TABLES, "COVERAGE.json"), encoding="utf-8"))
    fam = json.load(open(os.path.join(os.path.dirname(T.TABLES), "families.json"), encoding="utf-8"))
    script = {r["family"]: r["script"] for r in cov}
    keys = sorted(set(index["fonts"]) | set(script))
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for k in keys:
        r = T.route(k)
        if r is None:
            continue
        kind, name = r[0], r[1] if isinstance(r[1], str) else ""
        codes = {chr(c) for c in range(0x20, 0x100)} | {c for s in fam.values() for c in s.get(k, {}) if len(c) == 1} | set(T._labelled().get(k, {}))
        lines, texts = [], []
        for ch in sorted(codes):
            try:
                t = T.decode(k, ch)
            except Exception:
                continue
            if t is None or t == "":
                continue
            texts.append(t)
            name_ = unicodedata.name(t[0], "") if len(t) == 1 else ""
            lines.append(f"{fmt(ch)}\t{'+'.join(fmt(c) for c in unicodedata.normalize('NFC', t))}\t# {name_}")
        with open(os.path.join(OUT, f"{k}.tsv"), "w", encoding="utf-8") as f:
            f.write(f"# {k}: typed code -> Unicode ({kind} {name}); generated by tools/export_tables.py\n" + "\n".join(lines) + "\n")
        letters = collections.Counter(F.script_name(c) for t in texts for c in t if c.isalpha() and ord(c) > 0x7F)          # a font the corpus lists nowhere: the script it writes
        rows.append([k, script.get(k) or (letters.most_common(1)[0][0] if letters else ""), kind, name, len(lines), "yes" if kind in CONTEXT else "no", T._ocr().get("_source", {}).get(k, "")])
    with open(os.path.join(OUT, "index.tsv"), "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(["font", "script", "kind", "source", "codes", "context", "evidence"])
        w.writerows(rows)
    print(len(rows), "tables ->", OUT)


if __name__ == "__main__":
    main()
